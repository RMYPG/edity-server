// Writes emoji.go: the tables Prettier measures a line's width with, which
// decide where it breaks a line of a content file, from the Prettier of the
// edity checkout it is given, the one the Sites use. Run it with
//
//   mise run generate:emoji <edity>
import { writeFileSync } from 'node:fs';
import {
  emojiCodePoints,
  emojiStarts,
  emojiStrings,
  fullwidthRanges,
  narrowEmoji,
  version,
  wideRanges,
} from './prettier-bundle.mjs';

const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const printAtom = (atom) => {
  const cp = (n) => `\\x{${n.toString(16).toUpperCase()}}`;
  if (atom.char !== undefined) return cp(atom.char);
  if (atom.ranges) return `[${atom.ranges.map(([lo, hi]) => (lo === hi ? cp(lo) : `${cp(lo)}-${cp(hi)}`)).join('')}]`;
  return `(?:${printAlternatives(atom.group)})`;
};
const printAlternatives = (sequences) =>
  sequences.map((terms) => terms.map(({ atom, optional }) => printAtom(atom) + (optional ? '?' : '')).join('')).join('|');

// The pattern goes in a raw string literal, split into lines of whole
// alternatives so that a diff after a Prettier update stays readable.
const patternLines = emojiCodePoints.map((terms) => printAlternatives([terms]));

const numbers = (values, perLine) => {
  const lines = [];
  for (let n = 0; n < values.length; n += perLine) {
    lines.push(`\t${values.slice(n, n + perLine).map(hex).join(', ')},`);
  }
  return lines.join('\n');
};

writeFileSync(new URL('emoji.go', import.meta.url), `// Code generated by emoji.mjs from Prettier ${version}. DO NOT EDIT.

package content

// prettierVersion is the Prettier whose getStringWidth these tables are from.
const prettierVersion = "${version}"

// emojiPattern matches what emoji-regex matches, the emoji Prettier counts
// as two columns, or one for those in narrowEmoji.
var emojiPattern = []string{
${patternLines.map((line) => `\t\`${line}\`,`).join('\n')}
}

// emojiStarts are the code points a match of emojiPattern starts with, in
// order.
var emojiStarts = []rune{
${numbers(emojiStarts, 8)}
}

// narrowEmoji are the emoji Prettier counts as one column when one matches
// alone, in order.
var narrowEmoji = []rune{
${numbers(narrowEmoji, 8)}
}

// fullwidthRanges and wideRanges are get-east-asian-width's East Asian
// Fullwidth and Wide characters, two columns each: the first and last code
// point of each range, in order.
var fullwidthRanges = []rune{
${numbers(fullwidthRanges, 8)}
}

var wideRanges = []rune{
${numbers(wideRanges, 8)}
}
`);
process.stderr.write(`Prettier ${version}: ${emojiStrings.size} emoji sequences, ${narrowEmoji.length} narrow emoji\n`);
